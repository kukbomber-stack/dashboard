// --- Вычисляет положение "сегодня" на графике по годам (startYear = год первой точки) ---
// Возвращает afterIndex/frac для компонента Trend + подпись с реальной датой браузера/сервера.
export function getNowMarker(startYear: number, pointsCount: number) {
  const today = new Date();
  const y = today.getFullYear();
  const idx = Math.min(Math.max(y - startYear - 1, 0), pointsCount - 2); // точки = конец года; "сегодня" - между концом предыдущего и текущего года
  const daysInYear = ((y % 4 === 0 && y % 100 !== 0) || y % 400 === 0) ? 366 : 365;
  const startOfYear = new Date(y, 0, 0).getTime();
  const dayOfYear = Math.floor((today.getTime() - startOfYear) / 86400000);
  const frac = Math.min(Math.max(dayOfYear / daysInYear, 0), 1);
  const dd = String(today.getDate()).padStart(2, "0");
  const mm = String(today.getMonth() + 1).padStart(2, "0");
  return { afterIndex: idx, frac, label: `Сегодня · ${dd}.${mm}` };
}

